"""Generate the Python gRPC stubs from proto/ml/v1/ml.proto into app/gen.

    python scripts/gen_proto.py            (run from ml-service/, or from anywhere)

The stubs are never committed: they are generated here and in the Dockerfile from the
same .proto the Go code is generated from, so the two sides cannot drift apart.
"""
from __future__ import annotations

import pathlib
import re
import sys

from grpc_tools import protoc

ROOT = pathlib.Path(__file__).resolve().parents[1]
PROTO_DIR = ROOT.parent / "proto" / "ml" / "v1"
OUT = ROOT / "app" / "gen"


def main() -> int:
    proto = PROTO_DIR / "ml.proto"
    if not proto.exists():
        print(f"missing {proto}", file=sys.stderr)
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "__init__.py").write_text('"""Generated by scripts/gen_proto.py. Do not edit."""\n')
    rc = protoc.main([
        "grpc_tools.protoc", f"-I{PROTO_DIR}", f"--python_out={OUT}", f"--grpc_python_out={OUT}", str(proto),
    ])
    if rc != 0:
        return rc
    # grpc_tools writes `import ml_pb2 as ...`, which only works from the same directory.
    g = OUT / "ml_pb2_grpc.py"
    g.write_text(re.sub(r"^import ml_pb2 as", "from . import ml_pb2 as", g.read_text(), flags=re.M))
    print(f"generated {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
